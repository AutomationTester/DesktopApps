#!/usr/bin/env bash
# =============================================================================
# git_practice.sh  -  Day 5 : Git basics, branching and a merge conflict
# =============================================================================
# WHAT IT DOES
#   Creates a THROWAWAY Git repository in  examples/sandbox_repo/  and walks
#   through the everyday Git workflow, printing every command before it runs:
#
#     1. git init / git config (LOCAL to the sandbox only)
#     2. add / commit / status / log / diff
#     3. a feature branch that merges cleanly (fast-forward)
#     4. a DELIBERATE merge conflict between two branches
#     5. resolving the conflict and committing the merge
#     6. tagging a release and printing  git log --graph
#
# SAFETY
#   * It only ever deletes and re-creates its OWN folder: <script dir>/sandbox_repo
#   * It never touches your global git config (uses `git config --local`)
#   * It never talks to any remote (no push / pull / fetch)
#   * Running it again simply starts from scratch (idempotent)
#
# HOW TO RUN (Git Bash on Windows, or any Linux/macOS shell)
#   bash git_practice.sh
#   bash git_practice.sh --clean      # just delete the sandbox and exit
# =============================================================================

set -u                                  # error on undefined variables

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SANDBOX="$SCRIPT_DIR/sandbox_repo"

# ---------- helpers ----------------------------------------------------------
step() {                                # print a section heading
    echo
    echo "=================================================================="
    echo "== $*"
    echo "=================================================================="
}

run() {                                 # print a command, then run it
    echo
    echo "\$ $*"
    "$@"
}

# ---------- safety check before deleting anything ----------------------------
case "$(basename "$SANDBOX")" in
    sandbox_repo) ;;                    # expected name - OK
    *) echo "Refusing to continue: unexpected sandbox path '$SANDBOX'"; exit 1 ;;
esac

if [ -d "$SANDBOX" ]; then
    echo "Removing previous sandbox: $SANDBOX"
    rm -rf -- "$SANDBOX"
fi

if [ "${1:-}" = "--clean" ]; then
    echo "Sandbox cleaned. Bye."
    exit 0
fi

mkdir -p "$SANDBOX"
cd "$SANDBOX" || exit 1

# Make the output independent of the user's personal settings
export GIT_PAGER=cat                    # never open 'less'
export GIT_EDITOR=true                  # never open an editor
export GIT_MERGE_AUTOEDIT=no

# -----------------------------------------------------------------------------
step "1. Create a repository and configure it (local config only)"
# -----------------------------------------------------------------------------
run git init --initial-branch=main .
run git config --local user.name  "Trainee Tester"
run git config --local user.email "trainee@example.com"
run git config --local core.autocrlf false
run git config --local init.defaultBranch main
run git config --local --list

# -----------------------------------------------------------------------------
step "2. Working directory -> staging area -> repository"
# -----------------------------------------------------------------------------
cat > README.md <<'EOF'
# Sandbox Automation Repo
Practice repository created by git_practice.sh
EOF

cat > .gitignore <<'EOF'
# generated by test runs - never commit these
reports/
logs/
screenshots/
__pycache__/
.venv/
EOF

cat > greeting.py <<'EOF'
def greet(name):
    return "Hello " + name
EOF

run git status --short                  # ?? = untracked
run git add README.md .gitignore        # stage two files
run git status --short                  # A  = staged (added)
run git commit -m "docs: add README and .gitignore"
run git add greeting.py
run git commit -m "feat: add greet() helper"

# Ignored files never show up in status
mkdir -p reports logs
echo "<html>report</html>" > reports/report.html
echo "log line" > logs/run.log
run git status --short --ignored        # !! = ignored

# -----------------------------------------------------------------------------
step "3. See what changed: git diff (unstaged) vs git diff --staged"
# -----------------------------------------------------------------------------
cat > greeting.py <<'EOF'
def greet(name):
    """Return a friendly greeting."""
    return "Hello " + name
EOF
run git diff                            # working dir vs staging
run git add greeting.py
run git diff --staged                   # staging vs last commit
run git commit -m "docs: add docstring to greet()"
run git log --oneline

# -----------------------------------------------------------------------------
step "4. Feature branch that merges cleanly (fast-forward)"
# -----------------------------------------------------------------------------
run git switch -c feature/farewell
cat > farewell.py <<'EOF'
def farewell(name):
    return "Goodbye " + name
EOF
run git add farewell.py
run git commit -m "feat: add farewell() helper"
run git switch main
run git merge feature/farewell          # fast-forward, no conflict
run git branch -d feature/farewell      # tidy up merged branch
run git log --oneline --graph

# -----------------------------------------------------------------------------
step "5. A DELIBERATE merge conflict"
# -----------------------------------------------------------------------------
# Two branches change the SAME line of greeting.py in different ways.
run git switch -c feature/formal-greeting
cat > greeting.py <<'EOF'
def greet(name):
    """Return a friendly greeting."""
    return "Good morning, " + name
EOF
run git commit -am "feat: formal greeting"

run git switch main
cat > greeting.py <<'EOF'
def greet(name):
    """Return a friendly greeting."""
    return "Hi " + name + "!"
EOF
run git commit -am "feat: casual greeting"

echo
echo "\$ git merge feature/formal-greeting   (this is EXPECTED to fail)"
if git merge feature/formal-greeting; then
    echo "Unexpected: merge succeeded without conflict"
else
    echo
    echo ">>> CONFLICT! Git stopped the merge. Let's look at the damage:"
fi
run git status --short                  # UU = both modified (unmerged)
echo
echo "--- greeting.py with conflict markers ---"
cat greeting.py
echo "-----------------------------------------"

# -----------------------------------------------------------------------------
step "6. Resolve the conflict"
# -----------------------------------------------------------------------------
# In real life you edit the file in VS Code ("Accept Current / Incoming /
# Both") - here we write the agreed final version, then add + commit.
cat > greeting.py <<'EOF'
def greet(name, formal=False):
    """Return a friendly greeting (formal or casual)."""
    if formal:
        return "Good morning, " + name
    return "Hi " + name + "!"
EOF
echo "Resolved greeting.py:"
cat greeting.py
run git add greeting.py                 # mark as resolved
run git commit -m "merge: support formal and casual greetings"   # completes the merge
run git branch -d feature/formal-greeting

# -----------------------------------------------------------------------------
step "7. Tag a release and show history"
# -----------------------------------------------------------------------------
run git tag -a v1.0.0 -m "First stable sandbox release"
run git tag --list
run git log --oneline --graph --decorate --all
run git show --stat HEAD

step "DONE"
echo "Sandbox repository: $SANDBOX"
echo "Explore it yourself:  cd \"$SANDBOX\" && git log --graph --oneline"
echo "Delete it:            bash git_practice.sh --clean"
