"""
Day 4 - Example 03: Configuration-driven framework + environment handling
=========================================================================
One YAML file holds settings for every environment (dev, qa, ...).
The framework picks the environment from (highest priority first):
    1. command line argument  --env qa
    2. environment variable   TEST_ENV=qa
    3. default_env in the YAML file

The chosen environment decides the log level, timeouts, retry count etc.
A reusable get_logger() helper then builds a logger from that config.

Run:
    python 03_logger_config_from_yaml.py
    python 03_logger_config_from_yaml.py --env qa
    (PowerShell)  $env:TEST_ENV="qa"; python 03_logger_config_from_yaml.py
    (bash)        TEST_ENV=qa python 03_logger_config_from_yaml.py
"""
import argparse
import copy
import logging
import os
import sys
from datetime import datetime
from pathlib import Path

import yaml

HERE = Path(__file__).parent
CONFIG_FILE = HERE / "sample_config.yaml"

SAMPLE_YAML = """\
# Sample framework configuration (generated by 03_logger_config_from_yaml.py)
default_env: dev

common:                      # settings shared by all environments
  log_dir: logs
  log_format: "%(asctime)s | %(levelname)-8s | %(name)s | %(message)s"
  screenshot_on_failure: true

environments:
  dev:
    log_level: DEBUG
    timeout: 5
    retry_count: 1
    app:
      calculator: calc.exe
      data_folder: C:/temp/dev_data
  qa:
    log_level: INFO
    timeout: 15
    retry_count: 3
    app:
      calculator: calc.exe
      data_folder: D:/qa_share/data
"""


def ensure_sample_config():
    if not CONFIG_FILE.exists():
        CONFIG_FILE.write_text(SAMPLE_YAML, encoding="utf-8")


def resolve_env(cli_env=None, raw=None):
    """Priority: CLI > TEST_ENV variable > default_env."""
    return cli_env or os.environ.get("TEST_ENV") or raw.get("default_env", "dev")


def get_config(env=None, path=CONFIG_FILE):
    """Load YAML, merge 'common' with the chosen environment, return a flat dict."""
    with open(path, encoding="utf-8") as f:
        raw = yaml.safe_load(f)
    env = resolve_env(env, raw)
    if env not in raw["environments"]:
        raise ValueError(f"Unknown environment '{env}'. Valid: {list(raw['environments'])}")
    config = copy.deepcopy(raw.get("common", {}))
    config.update(raw["environments"][env])
    config["env"] = env
    return config


def get_logger(name, config):
    """Reusable helper: console + per-run file, level and format from config."""
    logger = logging.getLogger(name)
    if logger.handlers:                      # avoid duplicate handlers on repeat calls
        return logger
    logger.setLevel(config["log_level"])
    logger.propagate = False
    fmt = logging.Formatter(config["log_format"])

    console = logging.StreamHandler(sys.stdout)
    console.setFormatter(fmt)
    logger.addHandler(console)

    log_dir = HERE / config["log_dir"]
    log_dir.mkdir(exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    fh = logging.FileHandler(log_dir / f"config_demo_{config['env']}_{stamp}.log", encoding="utf-8")
    fh.setFormatter(fmt)
    logger.addHandler(fh)
    return logger


def main():
    parser = argparse.ArgumentParser(description="Config-driven logger demo")
    parser.add_argument("--env", help="environment name (dev/qa)")
    args = parser.parse_args()

    ensure_sample_config()
    config = get_config(args.env)
    log = get_logger("framework", config)

    print(f"Selected environment : {config['env']}")
    print(f"Timeout / retries    : {config['timeout']}s / {config['retry_count']}")
    print(f"Log level from config: {config['log_level']}")
    print("-" * 60)
    log.debug("DEBUG message - visible only in dev")
    log.info("INFO message  - visible in dev and qa")
    log.warning("Using data folder %s", config["app"]["data_folder"])

    for h in list(log.handlers):
        h.close()
        log.removeHandler(h)
    print("-" * 60)
    print("Change the environment and run again: python 03_logger_config_from_yaml.py --env qa")


if __name__ == "__main__":
    main()
